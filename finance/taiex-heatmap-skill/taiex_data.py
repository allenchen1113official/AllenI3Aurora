import hashlib

# 概略分級權重（僅作為無實際市值資料個股的退回值，範圍已加大以貼近真實
# 市值分布的高度集中特性）
TIER_WEIGHT = {1: 20, 2: 10, 3: 4, 4: 1.5, 5: 0.6, 6: 0.25}


def _det_variation(key, spread=1.1):
    """依代號產生可重現的小幅偏移量，避免同類股個股顏色完全一致。"""
    h = int(hashlib.md5(key.encode("utf-8")).hexdigest(), 16)
    frac = (h % 10000) / 10000.0  # 0..1
    return (frac * 2 - 1) * spread


def build_sector_data(sector_specs, sector_base, overrides, weight_override=None, cap=20.0, spread=1.1):
    """sector_specs: {sector: [(code,name,tier), ...]}
    weight_override: {code: 市值權重}，優先於 tier 概略分級"""
    weight_override = weight_override or {}
    data = {}
    for sector, stocks in sector_specs.items():
        base = sector_base.get(sector, 0.3)
        rows = []
        for code, name, tier in stocks:
            weight = weight_override.get(code, TIER_WEIGHT[tier])
            if code in overrides:
                pct = overrides[code]
            else:
                pct = base + _det_variation(code, spread)
                pct = max(-cap * 0.85, min(cap * 0.85, pct))
            rows.append((code, name, weight, round(pct, 2)))
        data[sector] = rows
    return data



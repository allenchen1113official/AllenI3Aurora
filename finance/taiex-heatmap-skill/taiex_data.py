def top_n_sectors(sector_specs, weight_override, n):
    """依市值權重（有覆寫值優先，否則用tier概略值）取前n大，
    依原本sector順序、股票順序重建 sector_specs 結構（無股票的sector會被移除）。"""
    flat = []
    for sector, stocks in sector_specs.items():
        for code, name, tier in stocks:
            w = weight_override.get(code, TIER_WEIGHT[tier])
            flat.append((w, code))
    flat.sort(key=lambda x: -x[0])
    top_codes = set(code for w, code in flat[:n])
    filtered = {}
    for sector, stocks in sector_specs.items():
        kept = [(code, name, tier) for code, name, tier in stocks if code in top_codes]
        if kept:
            filtered[sector] = kept
    return filtered


